#!/usr/bin/env node
/**
 * generate-e2e-example-pages.mjs
 *
 * The hand-written "Live example" doc components in docs/src/components/examples/
 * have no standalone HTML page, so the Playwright e2e suite cannot load them.
 * This script turns each one into a runnable page under examples/.e2e/ (git
 * ignored) by reusing the component's own `animate` (+ optional `createScene`):
 * it strips the React/ManimExample wrapper, repoints the `manim-web` import at
 * the local source, copies any local asset the component imports, and appends a
 * small bootstrap that builds the Scene and runs `animate`.
 *
 * The generated pages are consumed by tests/integration/all-examples.spec.ts.
 *
 * Usage: node scripts/generate-e2e-example-pages.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, copyFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const COMP = join(ROOT, 'docs', 'src', 'components', 'examples');
const OUT = join(ROOT, 'examples', '.e2e');

// Components whose scene cannot run headless without user input or hardware
// (audio, WebXR, gamepad, a video player, or an `animate` nested in the React
// body). They are exercised manually, not by the e2e content assertion.
const SKIP = new Set([
  'SonifierExample', // `animate` is defined inside the React component body
  'SpatialAudioExample',
  'WebXRExample',
  'GameInputExample',
  'PlayerExample',
  'SmilExportExample',
]);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const generated = [];
const skipped = [];
for (const file of readdirSync(COMP)) {
  if (!file.endsWith('.tsx')) continue;
  const name = file.replace(/\.tsx$/, '');
  const src = readFileSync(join(COMP, file), 'utf8');
  // Only the hand-written live components lack an HTML page; autogen ones (and
  // the hand-maintained export example) already have examples/*.html.
  if (src.includes('Auto-generated by generate-example-docs')) continue;
  if (SKIP.has(name)) {
    skipped.push(name);
    continue;
  }

  let body = src
    .replace(/^\s*import\s+React\s+from\s+'react';\s*$/m, '')
    .replace(/^\s*import\s+ManimExample\s+from\s+'[^']*';\s*$/m, '');

  // Copy any local asset the component imports (e.g. ./worldLand.json) and keep
  // the relative import working from the output dir.
  for (const m of body.matchAll(/from\s+'(\.\/[^']+\.(?:json|svg|png|jpg))'/g)) {
    const rel = m[1].slice(2);
    const from = join(COMP, rel);
    if (existsSync(from)) copyFileSync(from, join(OUT, rel));
  }

  const cut = body.indexOf('export default');
  if (cut !== -1) body = body.slice(0, cut);

  if (!/\bfunction\s+animate\s*\(|\bconst\s+animate\s*=/.test(body)) {
    skipped.push(name);
    continue;
  }
  body = body.replace(/(['"])manim-web\1/g, "'/src/index.ts'");
  const hasCreateScene = /function\s+createScene\s*\(|const\s+createScene\s*=/.test(body);

  const ts = `${body}
// ---- e2e bootstrap (generated) ----
(async () => {
  const container = document.getElementById('container');
  const W = 854, H = 480;
  const manim = await import('/src/index.ts');
  try {
    const scene = ${hasCreateScene
      ? 'await createScene(container, manim, { width: W, height: H })'
      : "new manim.Scene(container, { width: W, height: H, backgroundColor: '#000000' })"};
    window.__scene = scene;
    const run = Promise.resolve(animate(scene));
    run.then(() => { window.__done = true; }).catch((e) => {
      window.__err = String((e && e.message) || e);
      console.error('ANIMATE', e);
    });
    setTimeout(() => {
      try {
        if (scene._autoRender !== undefined) scene._autoRender = true;
        if (scene._render) scene._render();
      } catch { /* ignore */ }
      window.__ready = true;
    }, 1400);
  } catch (e) {
    window.__err = String((e && e.message) || e);
    console.error('INIT', e);
  }
})();
`;
  writeFileSync(join(OUT, `${name}.ts`), ts);
  writeFileSync(
    join(OUT, `${name}.html`),
    `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>${name}</title><style>
html,body{margin:0;padding:0;background:#000;width:100%;height:100%;overflow:hidden}
#container{width:854px;height:480px;margin:0 auto;display:flex;justify-content:center;align-items:center}
canvas,svg{max-width:100%;max-height:100%}
</style></head><body><div id="container"></div>
<script type="module" src="./${name}.ts"></script></body></html>`,
  );
  generated.push(name);
}

writeFileSync(join(OUT, '_manifest.json'), JSON.stringify({ generated, skipped }, null, 2));
console.log(`generated ${generated.length} e2e pages, skipped ${skipped.length}: ${skipped.join(', ')}`);
